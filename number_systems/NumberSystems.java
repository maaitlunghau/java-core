package number_systems;

public class NumberSystems {
    public static void main(String[] args) {
        int decimal = 152;
        int binary = 0b10011000;
        int octal = 0230;
        int hexadecimal = 0x98;

        System.out.println(decimal); // 152
        System.out.println(binary); // 152
        System.out.println(octal); // 152
        System.out.println(hexadecimal); // 152
    }
}
